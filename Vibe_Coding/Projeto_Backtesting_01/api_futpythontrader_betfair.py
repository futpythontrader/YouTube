pd.set_option('display.max_columns', None)

def drop_reset_index(df):
    df = df.dropna()
    df = df.reset_index(drop=True)
    df.index += 1
    return df

HEADERS = {"Authorization": f"Token {TOKEN}"}

"""### Betfair Exchange

##### Jogos do Dia
"""

FONTE = "betfair"
url_jogos = f"https://api.futpythontrader.com/api/dados/jogos-do-dia/{FONTE}/{DIA}/"

response = requests.get(url_jogos, headers=HEADERS)

if response.status_code == 200:
    data = response.json()
    print(f"Total de jogos: {data['total']}")

    df_jogos = pd.DataFrame(data['dados'])
    df_jogos = df_jogos.sort_values(by=['Date', 'Time'], ascending=[True, True])
    df_jogos = drop_reset_index(df_jogos)
    print("\n--- Jogos do Dia ---")
    display(df_jogos.tail())

else:
    print(f"Erro: {response.status_code}")

"""##### Base de Dados"""

FONTE = "betfair"
BASE_URL_DOWNLOAD = f"https://api.futpythontrader.com/api/dados/{FONTE}/download/"

def get_dataframe(params=None):
    print(f"Baixando dados da fonte '{FONTE}'.")
    response = requests.get(BASE_URL_DOWNLOAD, headers=HEADERS, params=params)

    if response.status_code == 200:
        df = pd.read_csv(io.BytesIO(response.content))
        print(f"Sucesso! DataFrame criado com {len(df)} linhas.")
        return df
    else:
        print(f"Erro na requisição: {response.status_code}")
        print(response.text)
        return pd.DataFrame()

base = get_dataframe(params={})

df = base.copy()
df = df.sort_values(by=['Date', 'Time'], ascending=[True, True])
df = drop_reset_index(df)
